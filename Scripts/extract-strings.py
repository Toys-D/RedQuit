#!/usr/bin/env python3
"""Собирает Resources/Localization/en.lproj/Localizable.strings из Sources/RedQuit/L10n.swift.

    python3 Scripts/extract-strings.py

Английский файл — эталон: тест LocalizationTests проверяет, что во всех остальных языках
те же ключи и те же подстановки (%@, %ld).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Sources/RedQuit/L10n.swift"
CORE = ROOT / "Sources/RedQuitCore/ExclusionRules.swift"
OUT = ROOT / "Resources/Localization/en.lproj/Localizable.strings"

# Описательные названия встроенных исключений переводятся; собственные имена — нет.
TRANSLATED_BUILTINS = {
    "com.apple.loginwindow", "com.apple.controlcenter", "com.apple.notificationcenterui",
    "com.apple.WindowManager", "com.apple.SecurityAgent", "com.apple.screencaptureui",
    "com.apple.universalcontrol", "com.apple.ScreenSaver.Engine",
}

swift_string = r'"((?:[^"\\]|\\.)*)"'
pairs = re.findall(r'(?:tr|format)\(\s*' + swift_string + r'\s*,\s*' + swift_string, SOURCE.read_text())
if not pairs:
    sys.exit("в L10n.swift не найдено ни одной строки")

builtins = re.findall(r'\.init\(bundleID: ' + swift_string + r', name: ' + swift_string + r'\)', CORE.read_text())
pairs += [("builtin." + bid, name) for bid, name in builtins if bid in TRANSLATED_BUILTINS]

seen = set()
lines = ["/* RedQuit — English (source). Generated by Scripts/extract-strings.py, do not edit by hand. */", ""]
for key, value in pairs:
    if key in seen:
        continue
    seen.add(key)
    lines.append(f'"{key}" = "{value}";')

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(seen)} строк → {OUT.relative_to(ROOT)}")
